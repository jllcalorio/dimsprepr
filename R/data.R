#' Example Direct-Injection Metabolomics Data Matrix
#'
#' A simulated numeric matrix of 60 injections x 80 features representing
#' raw peak intensities from a two-batch direct-injection mass spectrometry
#' experiment. Rows are samples in injection order; columns are features
#' (m/z bins). Use it with [dims_metadata].
#'
#' The simulation includes, so that every preprocessing step has something
#' to do:
#' \itemize{
#'   \item sample-specific dilution (for [run_normalize()]),
#'   \item a Treatment effect on features `mz_0001`--`mz_0010`,
#'   \item a batch 2 intensity shift and a within-batch signal decline along
#'     the injection order (for [run_driftBatchCorrect()]),
#'   \item about 3% zeros (below-detection values) in biological samples and
#'     three almost-empty features, `mz_0078`--`mz_0080` (for
#'     [run_filtermissing()] and [run_mvimpute()]).
#' }
#'
#' @format A numeric matrix with 60 rows and 80 columns. Row names are
#'   sample identifiers (`S01`--`S60`, matching `dims_metadata$Sample`);
#'   column names are feature labels (`mz_0001`--`mz_0080`).
#'
#' @source Simulated data; generated by `data-raw/dims_example.R` in the
#'   package source.
#'
#' @family example data
#' @seealso [run_DIpreprocess()] to preprocess it in one call.
#'
#' @examples
#' data(dims_data)
#' dim(dims_data)
#' mean(dims_data == 0)   # proportion of below-detection values
#'
#' @keywords datasets
"dims_data"

#' Example Sample Metadata for dims_data
#'
#' A data frame of sample-level metadata matching the rows of [dims_data].
#' Each of the two batches has 30 injections, starting and ending with a
#' pooled QC sample and with a QC every 6th injection (6 QCs per batch), the
#' layout QC-based drift correction needs. Biological samples alternate
#' between Control and Treatment.
#'
#' @format A data frame with 60 rows and 5 columns:
#' \describe{
#'   \item{Sample}{Character. Unique sample identifier (`S01`--`S60`).}
#'   \item{Group}{Character. Sample group: `"Control"` (24), `"Treatment"`
#'     (24), or `"QC"` (12).}
#'   \item{Batch}{Integer. Batch number (1 or 2).}
#'   \item{InjectionSequence}{Integer. Order of injection (1--60).}
#'   \item{SubjectID}{Character. Biological subject ID (`BIO01`--`BIO48`) for
#'     non-QC samples; `NA` for QC.}
#' }
#'
#' @source Simulated data; generated by `data-raw/dims_example.R` in the
#'   package source.
#'
#' @family example data
#' @seealso [run_DIpreprocess()], whose default column names match this
#'   data frame.
#'
#' @examples
#' data(dims_metadata)
#' table(dims_metadata$Group, dims_metadata$Batch)
#'
#' @keywords datasets
"dims_metadata"
